def list_flows(
    db_path: Path,
    project_id: str,
    *,
    endpoint_id: Optional[str] = None,
    status_code: Optional[int] = None,
    role_id: Optional[str] = None,
    source: Optional[str] = None,
    limit: Optional[int] = None,
) -> list[dict]:
    """
    Purpose:
        Return stored flows for a project with optional discovery filters.
        Primary lookup path for flow UUIDs used by show, export, replay,
        auth-config, and debugging.

    Input:
        db_path      — Path to the project's talos.db.
        project_id   — Project identifier; scopes the query.
        endpoint_id  — optional exact match on flows.endpoint_id.
        status_code  — optional exact match on HTTP status_code.
        role_id      — optional exact match on capture-time role UUID.
        source       — optional exact match on flow source label.
        limit        — optional max rows (most recent first). Must be > 0
                       when provided.

    Output:
        List of dicts ordered by captured_at DESC, each containing:
            id, method, host, path, status_code, role_id, role_name,
            source, captured_at, endpoint_id.
        role_name is the roles.name join result, or empty string when the
        role row is missing.

    Side effects:
        Read-only DB access.  Returns [] when the DB file does not exist.

    Raises:
        ValueError when limit is set and is not a positive integer.
    """
    if limit is not None and limit <= 0:
        raise ValueError(f"limit must be a positive integer, got {limit}")

    if not db_path.exists():
        return []

    clauses = ["f.project_id = ?"]
    params: list = [project_id]

    if endpoint_id is not None:
        clauses.append("f.endpoint_id = ?")
        params.append(endpoint_id)
    if status_code is not None:
        clauses.append("f.status_code = ?")
        params.append(status_code)
    if role_id is not None:
        clauses.append("f.role_id = ?")
        params.append(role_id)
    if source is not None:
        clauses.append("f.source = ?")
        params.append(source)

    where = " AND ".join(clauses)
    sql = f"""
        SELECT f.id, f.method, f.host, f.path, f.status_code,
               f.role_id, COALESCE(r.name, '') AS role_name,
               f.source, f.captured_at, f.endpoint_id
        FROM flows f
        LEFT JOIN roles r ON r.id = f.role_id
        WHERE {where}
        ORDER BY f.captured_at DESC
    """
    if limit is not None:
        sql += " LIMIT ?"
        params.append(limit)

    with sqlite3.connect(str(db_path)) as conn:
        conn.row_factory = sqlite3.Row
        rows = conn.execute(sql, params).fetchall()
    return [dict(row) for row in rows]


def cmd_flow_list(project: object, args: argparse.Namespace) -> None:
    """
    Purpose:
        List stored flows for the active project so operators can discover
        flow UUIDs for show, export, replay, and auth-config.
    Input:
        project — active Project instance (db_path, id).
        args    — parsed filters: endpoint, status_code, role, source, limit.
    Side effects:
        Reads flows/roles from DB; prints a table to stdout.
        Exits 1 when --role does not resolve or --limit is invalid.
    """
    db_path = project.db_path  # type: ignore[attr-defined]
    project_id = project.id    # type: ignore[attr-defined]

    role_id: str | None = None
    if args.role:
        role = resolve_role(db_path, args.role)
        if role is None:
            cli_error(f"Role '{args.role}' not found.")
        role_id = role["id"]

    try:
        flows = list_flows(
            db_path,
            project_id,
            endpoint_id=args.endpoint,
            status_code=args.status_code,
            role_id=role_id,
            source=args.source,
            limit=args.limit,
        )
    except ValueError as exc:
        cli_error(str(exc))

    if wants_json(args):
        cli_json(flows)
        return

    if not flows:
        print(
            "No flows match the given filters."
            if _has_list_filters(args)
            else "No flows captured yet."
        )
        return

    # Endpoint column: host + path for multi-host readability.
    def _endpoint_label(row: dict) -> str:
        host = row.get("host") or ""
        path = row.get("path") or ""
        return f"{host}{path}"

    def _status_label(row: dict) -> str:
        code = row.get("status_code")
        return str(code) if code is not None else "-"

    def _role_label(row: dict) -> str:
        name = row.get("role_name") or ""
        return name if name else (row.get("role_id") or "-")

    uuid_w = max(len("UUID"), max(len(f["id"] or "") for f in flows))
    ep_w = max(len("Endpoint"), max(len(_endpoint_label(f)) for f in flows))
    method_w = max(len("Method"), max(len(f.get("method") or "") for f in flows))
    status_w = max(len("Status"), max(len(_status_label(f)) for f in flows))
    role_w = max(len("Role"), max(len(_role_label(f)) for f in flows))
    source_w = max(len("Source"), max(len(f.get("source") or "") for f in flows))
    created_w = max(len("Created"), max(len(f.get("captured_at") or "") for f in flows))

    header = (
        f"{'UUID':<{uuid_w}}  {'Endpoint':<{ep_w}}  {'Method':<{method_w}}  "
        f"{'Status':<{status_w}}  {'Role':<{role_w}}  "
        f"{'Source':<{source_w}}  {'Created':<{created_w}}"
    )
    print(header)
    print("-" * len(header))
    for f in flows:
        print(
            f"{f['id']:<{uuid_w}}  "
            f"{_endpoint_label(f):<{ep_w}}  "
            f"{(f.get('method') or ''):<{method_w}}  "
            f"{_status_label(f):<{status_w}}  "
            f"{_role_label(f):<{role_w}}  "
            f"{(f.get('source') or ''):<{source_w}}  "
            f"{(f.get('captured_at') or ''):<{created_w}}"
        )
    print(f"\n{len(flows)} flow(s).")


def _has_list_filters(args: argparse.Namespace) -> bool:
    """
    Purpose:
        Detect whether the operator passed any list filter so empty results
        can print a more accurate message.
    Input:
        args — parsed flow list namespace.
    Output:
        True when at least one filter is set.
    Side effects: None.
    """
    return bool(
        args.endpoint
        or args.status_code is not None
        or args.role
        or args.source
    )


def _cmd_show(manager: ProjectManager, args: argparse.Namespace) -> None:
    """
    Purpose:
        Display a single replay flow with full request, response, and metadata.
    Side effects: Reads DB; prints to stdout (table text or JSON).
    """
    project = _require_active(manager)
    flow_id = args.flow_id
    flow = _fetch_flow(project.db_path, flow_id)
    if flow is None:
        cli_error(f"Flow '{flow_id}' not found.")
    if wants_json(args):
        # Enrich with parsed meta/headers for automation while keeping raw fields.
        payload = dict(flow)
        payload["flow_meta_parsed"] = _parse_flow_meta(flow)
        payload["request_headers_parsed"] = _parse_json(flow.get("request_headers", "{}"))
        payload["response_headers_parsed"] = _parse_json(flow.get("response_headers", "{}"))
        cli_json(payload)
        return
    print(_render_flow_text(flow))


def _cmd_export(manager: ProjectManager, args: argparse.Namespace) -> None:
    """
    Purpose:
        Export one or more flows to a Markdown file in <project_dir>/exports/.
    Side effects: Reads DB; writes Markdown file.
    """
    project = _require_active(manager)
    db_path = project.db_path

    flow_ids: list[str] = []

    if getattr(args, "flow_id", None):
        flow_ids = [args.flow_id]
    elif getattr(args, "flows", None):
        flow_ids = args.flows
    elif getattr(args, "module", None):
        flow_ids = _fetch_flow_ids_by_module(db_path, args.module)
    elif getattr(args, "parameter", None):
        flow_ids = _fetch_flow_ids_by_param_uuid(db_path, args.parameter)
    elif getattr(args, "endpoint", None):
        flow_ids = _fetch_flow_ids_by_endpoint(db_path, args.endpoint)
    else:
        cli_usage_error("Specify a flow_id, --module, --parameter, --endpoint, or --flows.")

    if not flow_ids:
        print("No flows found matching the specified scope.")
        return

    lines: list[str] = [f"# Flow Export — {len(flow_ids)} flows", ""]
    for fid in flow_ids:
        flow = _fetch_flow(db_path, fid)
        if flow is None:
            lines.append(f"## Flow `{fid[:8]}…`")
            lines.append(f"*(not found)*")
            lines.append("")
            continue
        lines.append(_render_flow_markdown(flow))
        lines.append("")

    md_content = "\n".join(lines)
    export_dir = _get_export_dir(project)
    # Build a descriptive filename.
    if len(flow_ids) == 1:
        fname = f"flow_{flow_ids[0][:16]}.md"
    elif getattr(args, "module", None):
        fname = f"flows_{args.module}.md"
    elif getattr(args, "parameter", None):
        fname = f"flows_param_{args.parameter[:16]}.md"
    elif getattr(args, "endpoint", None):
        fname = f"flows_endpoint_{args.endpoint[:16]}.md"
    else:
        fname = f"flows_export_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}.md"

    out_path = export_dir / fname
    out_path.write_text(md_content, encoding="utf-8")
    print(f"Exported {len(flow_ids)} flow(s) to {out_path}")


