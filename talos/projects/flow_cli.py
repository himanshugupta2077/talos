"""
Module: talos.projects.flow_cli

Purpose:
    Universal flow CLI — list, inspect, and export any stored flow regardless
    of which module generated it (proxy capture, Input Validation, BAC,
    manual replay, etc.).

    Every replay flow is self-describing via the flow_meta JSON column
    introduced in schema v27.  This CLI exposes that data.

    Commands:
        talos flow list                  — inventory of captured/replay flows
        talos flow show <flow_id>        — display full request/response + meta
        talos flow export <flow_id>      — write Markdown file to project exports/
        talos flow export --module iv    — export all IV flows
        talos flow export --param <uuid> — export all flows for a parameter UUID

Dependencies: argparse, json, sqlite3, sys, talos.projects.access
Data flow:
    CLI args → DB reads (flows + roles + flow_meta) → stdout or export file
Side effects:
    - Read-only DB access.
    - export command writes a Markdown file to <project_dir>/exports/.
    - Exits 1 on error.
"""
from talos.cli_output import (
    add_format_argument,
    cli_error,
    cli_json,
    cli_usage_error,
    cli_precondition_error,
    wants_json,
)

import argparse
import json
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from talos.projects.access import resolve_role
from talos.projects.manager import ProjectManager


def _require_active(manager: ProjectManager):
    project = manager.active()
    if project is None:
        cli_precondition_error("No active project. Run 'talos project open <id>', or pass --project <id> / set TALOS_PROJECT.")
    return project


def run_flow_cli(manager: ProjectManager, argv: list[str]) -> None:
    """
    Purpose:
        Parse flow subcommand arguments and dispatch to handler.
    Input:
        manager — ProjectManager instance.
        argv    — argument list after 'flow'.
    Side effects:
        Dispatches to command handlers.  Exits 0 for --help, 1 for errors.
    """
    parser = argparse.ArgumentParser(
        prog="talos flow",
        description=(
            "Universal flow inspector.  Works for any stored flow regardless "
            "of source (proxy capture, IV, BAC, manual replay, etc.)."
        ),
    )
    sub = parser.add_subparsers(dest="flow_cmd", metavar="<command>")
    sub.required = True

    # ------------------------------------------------------------------
    # list
    # ------------------------------------------------------------------
    p_list = sub.add_parser(
        "list",
        help="List captured and replay flows (UUID, endpoint, method, status, role, source).",
    )
    p_list.add_argument(
        "--endpoint",
        default=None,
        metavar="ENDPOINT_ID",
        help="Filter by endpoint UUID.",
    )
    p_list.add_argument(
        "--status-code",
        default=None,
        type=int,
        metavar="CODE",
        help="Filter by HTTP status code (exact match).",
    )
    p_list.add_argument(
        "--role",
        default=None,
        metavar="NAME|UUID",
        help="Filter by role name or UUID (capture-time role).",
    )
    p_list.add_argument(
        "--source",
        default=None,
        metavar="SOURCE",
        help=(
            "Filter by flow source "
            "(proxy_capture | manual_replay | auto_replay | iv_scan)."
        ),
    )
    p_list.add_argument(
        "--limit",
        default=None,
        type=int,
        metavar="N",
        help="Return at most N flows (most recent first).",
    )
    add_format_argument(p_list)

    # ------------------------------------------------------------------
    # show
    # ------------------------------------------------------------------
    p_show = sub.add_parser("show", help="Display a replay flow (request + response + metadata).")
    p_show.add_argument("flow_id", help="UUID of the replay flow.")
    add_format_argument(p_show)

    # ------------------------------------------------------------------
    # export
    # ------------------------------------------------------------------
    p_export = sub.add_parser(
        "export",
        help="Export one or more replay flows to Markdown.",
    )
    scope_grp = p_export.add_mutually_exclusive_group()
    scope_grp.add_argument("flow_id", nargs="?", help="Single flow UUID to export.")
    scope_grp.add_argument(
        "--module",
        metavar="MODULE",
        help="Export all flows generated by a module (e.g. input_validation, bac).",
    )
    scope_grp.add_argument(
        "--parameter",
        metavar="PARAM_UUID",
        help="Export all IV flows for a parameter UUID.",
    )
    scope_grp.add_argument(
        "--endpoint",
        metavar="ENDPOINT_ID",
        help="Export all flows for an endpoint UUID.",
    )
    scope_grp.add_argument(
        "--flows",
        nargs="+",
        metavar="FLOW_ID",
        help="Export a list of flow UUIDs.",
    )

    args = parser.parse_args(argv)

    if args.flow_cmd == "list":
        project = _require_active(manager)
        cmd_flow_list(project, args)
    elif args.flow_cmd == "show":
        _cmd_show(manager, args)
    elif args.flow_cmd == "export":
        _cmd_export(manager, args)
    else:
        parser.print_help()
        sys.exit(1)


