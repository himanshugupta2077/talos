# Prefer this order when choosing a single primary category for multi-match.
_PRIMARY_PRIORITY: tuple[str, ...] = (
    CATEGORY_OAUTH,
    CATEGORY_WEBHOOK,
    CATEGORY_REDIRECT,
    CATEGORY_IMPORT_METADATA,
    CATEGORY_REMOTE_ASSET,
    CATEGORY_NETWORK_PROBE,
    CATEGORY_INFRASTRUCTURE,
    CATEGORY_PATH_LIKE,
    CATEGORY_REMOTE_FETCH,
)


def primary_category(categories: list[str] | tuple[str, ...]) -> str | None:
    """
    Purpose:
        Pick one primary category from a multi-match list using stable priority.
    Input:
        categories — matching category ids (any order).
    Output:
        Primary category string, or None if empty.
    Side effects: None.
    """
    if not categories:
        return None
    present = set(categories)
    for cat in _PRIMARY_PRIORITY:
        if cat in present:
            return cat
    return categories[0]
