"""
Module: talos.url_sink.catalog

Purpose:
    Categorized parameter-name dictionaries for URL Sink Discovery.
    Replaces flat open_redirect / SSRF token lists with multi-category
    membership. Categories bias candidate *family* later; they do not
    alone invent a confirmed sink.

    Matching is case-insensitive after camelCase / snake / kebab normalization
    (see name_classify.normalize_param_name).

Categories:
    redirect          — open redirect / return / navigate surfaces
    webhook           — callback / hook / notify receivers
    remote_fetch      — generic URL/URI/endpoint/origin/fetch sinks
    remote_asset      — avatar / image / media / CDN asset URLs
    import_metadata   — feed / WSDL / schema / metadata import
    infrastructure    — backend / proxy / gateway / host / cluster
    network_probe     — healthcheck / probe / DNS / resolve
    path_like         — path / filepath / document / download
    oauth             — redirect_uri / return_uri style OAuth params

Dependencies: None (data only)
Data flow: imported by name_classify
Side effects: None.
"""

